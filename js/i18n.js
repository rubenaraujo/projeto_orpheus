let lang = localStorage.getItem('looper:lang') === 'pt' ? 'pt' : 'en';
const tr = (pt, ...a) => {
  let s = lang === 'pt' ? pt : (EN[pt] ?? pt);
  a.forEach((v, i) => { s = s.split('{' + i + '}').join(v); });
  return s;
};
const SKIP = '[data-dyn],script,style,svg,#list,#lib,#fsChips,#pChips,#recent,#resList,#toasts,#tlTip,textarea';
const ATTR = { title: 'ptTitle', 'aria-label': 'ptAria', placeholder: 'ptPh' };
function translateDom() {
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT), nodes = [];
  while (w.nextNode()) nodes.push(w.currentNode);
  nodes.forEach(n => {
    if (!n.nodeValue.trim() || n.parentElement.closest(SKIP)) return;
    n._pt ??= n.nodeValue;
    const m = n._pt.match(/^(\s*)([\s\S]*?)(\s*)$/);
    n.nodeValue = m[1] + tr(m[2]) + m[3];
  });
  document.querySelectorAll('[title],[aria-label],[placeholder]').forEach(el => {
    if (el.closest('[data-dyn],#list,#lib,#fsChips,#pChips,#recent,#resList')) return;
    Object.keys(ATTR).forEach(a => {
      if (!el.hasAttribute(a)) return;
      el.dataset[ATTR[a]] ??= el.getAttribute(a);
      el.setAttribute(a, tr(el.dataset[ATTR[a]]));
    });
  });
}
function applyLang() {
  document.documentElement.lang = lang;
  document.querySelectorAll('#langCtl button').forEach(b => b.classList.toggle('on', b.dataset.l === lang));
  translateDom();
  $('autoMsg').textContent = '';
  renderAll();
  if (typeof found !== 'undefined' && found.length) renderResults(); else $('resMsg').textContent = '';
  renderRecent();
  renderMastery();
  ['play', 'fsPlay', 'mPlay'].forEach(id => $(id).setAttribute('aria-label', tr($(id).querySelector('use').getAttribute('href') === '#i-pause' ? 'Pausa' : 'Play')));
}
document.querySelectorAll('#langCtl button').forEach(b => b.onclick = () => {
  lang = b.dataset.l; localStorage.setItem('looper:lang', lang); applyLang();
});
